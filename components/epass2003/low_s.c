#include "epass2003.h"
#include <string.h>
static const uint8_t order[32] = {
 0xff,0xff,0xff,0xff,0x00,0x00,0x00,0x00,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,
 0xbc,0xe6,0xfa,0xad,0xa7,0x17,0x9e,0x84,0xf3,0xb9,0xca,0xc2,0xfc,0x63,0x25,0x51};
static const uint8_t half[32] = {
 0x7f,0xff,0xff,0xff,0x80,0x00,0x00,0x00,0x7f,0xff,0xff,0xff,0xff,0xff,0xff,0xff,
 0xde,0x73,0x7d,0x56,0xd3,0x8b,0xcf,0x42,0x79,0xdc,0xe5,0x61,0x7e,0x31,0x92,0xa8};
int ep_low_s(uint8_t sig[64]) {
    uint8_t zero[32]={0};
    if (!memcmp(sig,zero,32) || !memcmp(sig+32,zero,32) ||
        memcmp(sig,order,32)>=0 || memcmp(sig+32,order,32)>=0) return EP_FORMAT;
    if (memcmp(sig+32,half,32)>0) {
        unsigned borrow=0;
        for (int i=31;i>=0;i--) {
            unsigned sub=(unsigned)sig[32+i]+borrow;
            sig[32+i]=(uint8_t)((unsigned)order[i]-sub);
            borrow=(unsigned)order[i]<sub;
        }
    }
    return 0;
}
